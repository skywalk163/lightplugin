"""生成 lightplugin/集成/宿主冒烟.light

与「全量挂载.light」的区别
==========================
全量挂载.light 证明的是「60 个插件能挂进同一个注册表、工具数守恒、无同名覆盖」，
执行冒烟是**直接调 execute**，绕过了宿主流水线。

宿主冒烟.light 证明的是**真正接进 lightharness 运行时**：
  - 用 `lightharness/src/工具.light` 的**真 工具注册表**（不是自建桩）
  - 走**完整执行流水线** 注册表.执行(名字, 参数)：
    解析参数 → prepare 钩子 → **宿主 JSON Schema 校验** → execute → finalize → 统计
  - 全覆盖派发 100 个工具（空参），看宿主校验器是否真的拦住缺必填
  - 定向用例：正确参数 → 期望 isError == 假
  - 异常路径：未知工具 → 期望 TOOL_NOT_FOUND

用法：
    python lightplugin/集成/生成宿主冒烟.py
    python lightplugin/运行.py 集成/宿主冒烟.light
"""
