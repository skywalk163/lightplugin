def 插件清单():
    out = []
    for name in sorted(os.listdir(PLUGINS)):
        d = os.path.join(PLUGINS, name)
        if not os.path.isdir(d) or name.startswith(("_", ".")):
            continue
        if not os.path.isfile(os.path.join(d, name + ".light")):
            continue
        out.append(name)
    return out


